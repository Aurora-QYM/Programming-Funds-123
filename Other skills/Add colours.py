def do_greeting(name):
    # 加粗 + 蓝色文字
    print(f"\033[1;34mGood morning , {name}\033[0m")
    # 下划线 + 黄色文字
    print(f"\033[4;33mGood morning , {name}\033[0m")
    # 红色文字 + 白色背景
    print(f"\033[31;47mGood morning , {name}\033[0m")

do_greeting('Dave')
do_greeting('Kevin')
